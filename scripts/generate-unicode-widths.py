"""Generate cell widths matched to the bundled Noto Sans Mono CJK TC font."""
import json
import pathlib
import struct
import unicodedata

root = pathlib.Path(__file__).resolve().parent.parent
font = (root / 'src/fonts/NotoSansMonoCJKtc-Regular.otf').read_bytes()
u16 = lambda p: struct.unpack_from('>H', font, p)[0]
u32 = lambda p: struct.unpack_from('>I', font, p)[0]
tables = {font[12+i*16:16+i*16].decode(): u32(20+i*16) for i in range(u16(4))}
cmap = tables['cmap']
subtable = next(cmap + u32(cmap+8+i*8) for i in range(u16(cmap+2))
                if u16(cmap+u32(cmap+8+i*8)) == 12)
metrics_count = u16(tables['hhea']+34)
units = u16(tables['head']+18)
advances = {}
for i in range(u32(subtable+12)):
    start, end, glyph = struct.unpack_from('>III', font, subtable+16+i*12)
    for cp in range(start, end+1):
        advances[cp] = u16(tables['hmtx']+min(glyph+cp-start, metrics_count-1)*4)

def ranges(points):
    result = []
    for cp in points:
        if result and cp == result[-1][1]+1:
            result[-1][1] = cp
        else:
            result.append([cp, cp])
    return result

zero, wide = [], []
for cp in range(0x110000):
    char = chr(cp)
    category = unicodedata.category(char)
    if category in ('Cc', 'Cf', 'Mn', 'Me') or 0x1160 <= cp <= 0x11ff:
        zero.append(cp)
    elif (advances.get(cp, 0) >= units or
          cp not in advances and category != 'Cn' and unicodedata.east_asian_width(char) in ('W', 'F')):
        wide.append(cp)
header = '// Generated by scripts/generate-unicode-widths.py; do not edit by hand.\n'
header += '// Font advances: Noto Sans Mono CJK TC; fallback Unicode ' + unicodedata.unidata_version + '.\n'
text = header + 'export const ZERO_WIDTH = ' + json.dumps(ranges(zero), separators=(',', ':')) + ';\n'
text += 'export const WIDE = ' + json.dumps(ranges(wide), separators=(',', ':')) + ';\n'
(root / 'src/unicode-width-data.js').write_text(text)
print('Generated', len(ranges(zero)), 'zero-width ranges and', len(ranges(wide)), 'wide ranges')
